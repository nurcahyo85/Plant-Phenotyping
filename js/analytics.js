// ===== UTILITY FUNCTIONS =====
function generateCSV(measurements) {
  const headers = ['Measurement #', 'Distance (µm)', 'Start X', 'Start Y', 'End X', 'End Y'];
  const rows = measurements.map((m, i) => [
    i + 1,
    m.dist,
    m.x1,
    m.y1,
    m.x2,
    m.y2,
  ]);

  const csv = [
    headers.join(','),
    ...rows.map((row) => row.map((cell) => `"${cell}"`).join(',')),
  ].join('\n');

  return csv;
}

function generateReport() {
  const now = new Date();
  const dateStr = now.toLocaleDateString('id-ID', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const report = `
LAPORAN ANALISIS FENOTIPE MIKROSKOPI
PlantScope v1.0
=====================================

Tanggal: ${dateStr}
Waktu: ${now.toLocaleTimeString('id-ID')}

1. RINGKASAN EKSEKUTIF
---------------------
Analisis morfometri dilakukan dengan total ${AppState.measurements.length} pengukuran.
Kalibrasi: ${AppState.pixPerUm} px/µm

2. DATA PENGUKURAN
-----------------
${
  AppState.measurements.length > 0
    ? AppState.measurements
        .map(
          (m, i) => `Pengukuran ${i + 1}: ${m.dist} µm (dari ${m.x1},${m.y1} ke ${m.x2},${m.y2})`
        )
        .join('\n')
    : 'Tidak ada pengukuran'
}

3. ANOTASI
----------
Total anotasi: ${AppState.annotations.length}

4. KESIMPULAN
-------------
Analisis selesai dan data telah dicatat.
Untuk hasil lebih detail, lihat data export JSON atau CSV.

=====================================
Generated by PlantScope
`;

  return report;
}

function downloadFile(content, filename, mimeType) {
  try {
    const blob = new Blob([content], { type: mimeType });
    const url = window.URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    window.URL.revokeObjectURL(url);
    document.body.removeChild(a);
  } catch (error) {
    console.error('Error downloading file:', error);
    throw error;
  }
}
