// ===== CSV EXPORT =====
function exportMeasurements() {
  try {
    if (AppState.measurements.length === 0) {
      alert('No measurements to export');
      return;
    }

    const csvContent = generateCSV(AppState.measurements);
    downloadFile(csvContent, 'measurements.csv', 'text/csv');
  } catch (error) {
    console.error('Error exporting measurements:', error);
    alert('Error exporting measurements');
  }
}

function exportAllCSV() {
  try {
    // Placeholder: Export all session data as CSV
    const data = {
      measurements: AppState.measurements,
      timestamp: new Date().toISOString(),
    };

    const csvContent = JSON.stringify(data, null, 2);
    downloadFile(csvContent, 'all-data.csv', 'text/csv');
  } catch (error) {
    console.error('Error exporting all CSV:', error);
    alert('Error exporting data');
  }
}

// ===== JSON EXPORT =====
function exportJSON() {
  try {
    const data = {
      measurements: AppState.measurements,
      annotations: AppState.annotations,
      calibration: AppState.pixPerUm,
      timestamp: new Date().toISOString(),
      version: '1.0',
    };

    const jsonContent = JSON.stringify(data, null, 2);
    downloadFile(jsonContent, 'phenotyping-data.json', 'application/json');
  } catch (error) {
    console.error('Error exporting JSON:', error);
    alert('Error exporting JSON');
  }
}

